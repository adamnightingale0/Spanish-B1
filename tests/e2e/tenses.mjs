// Tenses section + flashcard answer check. Run against preview: node tests/e2e/tenses.mjs http://localhost:4173/ [shotsDir]
import { createRequire } from 'node:module';
const { chromium, devices } = createRequire(import.meta.url)('playwright');
const [url = 'http://localhost:4173/', shots] = process.argv.slice(2);
const browser = await chromium.launch();
const page = await (await browser.newContext({ ...devices['iPhone 13'], deviceScaleFactor: 1 })).newPage();
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
const shot = (n) => shots && page.screenshot({ path: `${shots}/${n}.png`, fullPage: true });
const ok = (c, m) => { console.log((c ? '✓ ' : '✗ ') + m); if (!c) process.exitCode = 1; };

await page.goto(url + '#/practice');
await page.click('text=Tiempos verbales');
await page.waitForSelector('text=Mezcla de tiempos');
ok((await page.locator('.card.tap:not(.highlight)').count()) === 12, '12 tenses listed');
await shot('t-list');
await page.click('.card.tap:has-text("Pretérito indefinido")');
await page.waitForSelector('text=Cuándo NO se usa');
ok((await page.locator('table.simple').count()) === 2, 'model table + conjugator');
await page.selectOption('select', 'tener');
ok((await page.locator('table.simple >> nth=1').innerText()).includes('tuve'), 'conjugator shows tuve');
await shot('t-detail');
await page.click('button:has-text("Practicar formas")');
await page.waitForSelector('.answer-input');
const verb = await page.locator('.drill-top ~ * b').first().innerText().catch(() => '');
await page.fill('.answer-input', 'zzz');
await page.click('button:has-text("Comprobar")');
await page.waitForTimeout(200);
await shot('t-forms');
ok(errors.length === 0, `forms drill runs (${verb})`);
await page.goto(url + '#/tenses/subjuntivo');
await page.click('button:has-text("Practicar el uso")');
await page.waitForSelector('.drill-top');
await shot('t-use');
await page.goto(url + '#/tenses');
await page.click('button:has-text("Mezcla de tiempos")');
await page.waitForSelector('.drill-top');
// Irregular indefinido flashcards
await page.goto(url + '#/tenses');
await page.click('text=Tarjetas: indefinidos irregulares');
await page.waitForSelector('text=para repasar');
await shot('c-home');
await page.click('button:has-text("Estudiar")');
await page.waitForSelector('.flashcard .answer-input');
const verb1 = await page.locator('.fc-main').innerText();
await page.fill('.answer-input', 'fui');
await page.click('button:has-text("Comprobar")');
await page.waitForSelector('.feedback');
ok((await page.locator('.feedback').innerText()).includes(' = '), `meaning shown after checking (${verb1})`);
ok(await page.locator('.feedback table tr').count() === 6, 'full verb shown');
await shot('c-check');
await page.click('button:has-text("Siguiente")');
await page.fill('.answer-input', 'zzz');
await page.click('button:has-text("Comprobar")');
await page.click('button:has-text("Era una errata")');
ok(await page.locator('.feedback.ok').count() === 1, 'typo override marks it right');
await page.click('button:has-text("Siguiente")');
await page.click('.drill-top button');
await page.waitForSelector('text=para repasar');
ok(errors.length === 0, 'no page errors' + (errors.length ? ': ' + errors.join(' | ') : ''));
await browser.close();
